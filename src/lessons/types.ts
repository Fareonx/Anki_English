// Grammar lessons ("Уроки" tab). Content is plain data so it can be checked and tested.

/** A table of forms, e.g. a conjugation: head ['', 'presente'], rows [['io', 'sono'], ...]. */
export interface FormTable {
  title?: string;
  head: string[];
  rows: string[][];
}

export interface Example {
  /** The sentence in the language studied. */
  it: string;
  ru: string;
  az: string;
}

/** One exercise item: the student types `answer` (accents and apostrophes are not required). */
export interface Drill {
  /** What to do, e.g. "essere · noi" or "Io ___ (andare) a Bologna." */
  prompt: string;
  answer: string;
  /** Other accepted answers, e.g. "sono andata" next to "sono andato". */
  also?: string[];
  /** Short Russian hint shown after a wrong answer. */
  hint?: string;
}

export interface LessonSection {
  title: string;
  /** Explanation in Russian. Paragraphs separated by blank lines; **bold** is allowed. */
  text: string;
  tables?: FormTable[];
  examples?: Example[];
}

export interface Lesson {
  /** Stable id, e.g. "u02-modali". Progress is stored under it. */
  id: string;
  /** Unit of the textbook: 0 for "Benvenuti!", 1..11. */
  unit: number;
  title: string;
  /** One line: what you will be able to do. */
  goal: string;
  sections: LessonSection[];
  drills: Drill[];
}

export interface Unit {
  unit: number;
  /** Title as in the textbook, e.g. "Un nuovo inizio". */
  title: string;
  /** Russian title. */
  ru: string;
}

/** A verb of the trainer (src/lessons/<lang>/verbs.ts is generated by scripts/build_verbs.py). */
export interface Verb {
  inf: string;
  ru: string;
  az: string;
  /** Id of a group of the course, e.g. 'are' or 'irregular'. */
  group: string;
  /**
   * Per tense id, the forms for the six persons of the course. Each cell lists every correct
   * form, the main one first (masculine before feminine: "sono andato", "sono andata").
   * An empty cell has no form (the imperative has only some persons).
   */
  forms: Record<string, string[][]>;
}

export interface VerbTense {
  id: string;
  /** Russian name, e.g. "Presente — настоящее". */
  label: string;
  /** Unit of the course where the tense is taught. */
  unit: number;
}

/** Everything the "Уроки" tab shows for one language. */
export interface Course {
  units: Unit[];
  lessons: Lesson[];
  verbs: Verb[];
  tenses: VerbTense[];
  /** The six persons in tables and drills, e.g. "io", "tu", "lui / lei"... */
  persons: string[];
  groups: { id: string; label: string }[];
}

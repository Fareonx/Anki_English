const DICTS: Record<Lang, Dict> = { ru, az, en };

export const INTERVAL_UNITS: Record<Lang, IntervalUnits> = {
  ru: { lessMin: '<1 мин', min: 'мин', hour: 'ч', day: 'д', month: 'мес', year: 'г', decimal: ',' },
  az: { lessMin: '<1 dəq', min: 'dəq', hour: 'saat', day: 'gün', month: 'ay', year: 'il', decimal: ',' },
  en: { lessMin: '<1 min', min: 'min', hour: 'h', day: 'd', month: 'mo', year: 'y', decimal: '.' },
};

const LOCALES: Record<Lang, string> = { ru: 'ru-RU', az: 'az-Latn-AZ', en: 'en-GB' };

function pluralIndex(lang: Lang, n: number): number {
  if (lang === 'az') return 0;
  if (lang === 'en') return n === 1 ? 0 : 1;
  const m10 = n % 10;
  const m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return 0;
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return 1;
  return 2;
}

export function translate(lang: Lang, key: Key, vars: Record<string, string | number> = {}): string {
  let value = DICTS[lang][key] ?? ru[key];
  if (Array.isArray(value)) {
    const n = Number(vars.n ?? 0);
    value = value[Math.min(pluralIndex(lang, n), value.length - 1)];
  }
  return (value as string).replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`));
}

const STORAGE_KEY = 'lang';

function readLang(): Lang {
  try {
    const v = localStorage.getItem(STORAGE_KEY);
    return v === 'az' || v === 'en' ? v : 'ru';
  } catch {
    return 'ru';
  }
}

interface I18n {
  lang: Lang;
  locale: string;
  units: IntervalUnits;
  setLang: (lang: Lang) => void;
  t: (key: Key, vars?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18n | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(readLang);

  // The lang attribute makes upper-casing right for Azerbaijani (i → İ).
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = useCallback((next: Lang) => {
    setLangState(next);
    try {
      localStorage.setItem(STORAGE_KEY, next);
    } catch {
      // Storage unavailable: the choice lasts for this visit only.
    }
  }, []);

  const value = useMemo<I18n>(
    () => ({
      lang,
      locale: LOCALES[lang],
      units: INTERVAL_UNITS[lang],
      setLang,
      t: (key, vars) => translate(lang, key, vars),
    }),
    [lang, setLang],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18n {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used inside I18nProvider');
  return ctx;
}
